package com.kitwlshcom.kdailyutil.data

/**
 * 지문이 **어디서 온 글인지**를 화면이 말하게 한다 (2026-09-21 · 사용자 제기).
 *
 * 🔴 **왜 필요한가** — 앱은 남의 글을 가져다 쓰지 않는데, **화면이 그 말을 한 적이 없다.**
 * 읽는 사람 입장에서 「이 글 어디서 났지? 출처를 안 밝혀도 되나?」는 자연스러운 의심이고,
 * 의심이 남으면 «믿고 쓰는 앱»이 되지 못한다. 표기는 법적 방어가 아니라 **정직의 문제**다.
 *
 * ✅ **실제로 확인한 사실**(추측이 아니다):
 * - **로봇 지문**([ROBOT]) — `korean_quiz_data/update_passages.py`의 프롬프트가
 *   «실존 작품·기사·가사·시·소설의 문장을 그대로 쓰거나 요약·번안하지 말 것 · 새로 쓴 글만»,
 *   «실존 인물·상표·기업 이름 금지»를 못 박는다. 즉 **AI가 그 자리에서 지은 창작 산문**이고
 *   **옮겨 온 원문이 아니다** → 밝힐 «출처»가 애초에 없다. 밝힐 것은 «AI가 지었다»는 사실이다.
 * - **내장 지문**([BUILT_IN]) — `ReadingTrainingScreen.kt`의 19편. 주석 그대로
 *   «직접 작성한 원문 — 저작권 안전»이다. 통신이 안 될 때 떨어질 바닥으로 남겨 둔다.
 * - **내 지문**([MINE]) — 사용자가 **찍거나 붙여 넣은** 글. 이것만 출처가 앱 밖에 있고,
 *   그 판단(저작물인지·써도 되는지)은 **넣은 사람 몫**이다. 그래서 문구가 다르다.
 *
 * ⚠️ **글마다 «출처: ○○○»를 붙이지 않는다.** 로봇 지문은 전부 같은 출신이라 줄마다 같은 말을
 * 반복하면 **소음이 되고 정작 안 읽힌다.** → 갈래가 바뀌는 자리(목록 머리·오늘의 지문 카드)에서
 * **한 번씩** 말한다.
 *
 * 안드로이드 API를 쓰지 않는 순수 열거형이다(단위 테스트 대상).
 */
enum class PassageSource(
    /** 목록·카드에 붙는 짧은 꼬리표 — 「🤖 AI가 지은 글」 */
    val badge: String,
    /** 왜 그런지 한 줄로. 꼬리표만으로는 «그래서 뭐?»가 남는다. */
    val notice: String
) {
    /** 매일 로봇이 보내 주는 지문. */
    ROBOT(
        badge = "🤖 AI가 지은 글",
        notice = "매일 오는 지문은 AI가 새로 지은 창작 글이에요. 기사·소설·가사처럼 출처가 있는 글을 옮겨 오지 않습니다."
    ),

    /** 앱에 넣어 둔 19편(오프라인 폴백). */
    BUILT_IN(
        badge = "📗 앱 기본 지문",
        notice = "앱에 넣어 둔 연습용 원문이에요. 인터넷이 안 될 때 이 글이 나옵니다."
    ),

    /** 사용자가 촬영·붙여넣기로 담은 글. */
    MINE(
        badge = "📚 내가 넣은 글",
        notice = "내가 찍거나 붙여 넣은 글이에요. 남의 저작물을 담았다면 개인 연습 용도로만 쓰세요 — 앱은 이 글을 어디에도 올리지 않습니다."
    );

    companion object {
        /**
         * 「📜 긴 지문」이든 짧은 지문이든 **출신은 같다** — 길이로 출처가 갈리지 않는다.
         * 🔴 이 함수가 있는 이유는 그 사실을 코드로 못 박아 두기 위해서다.
         * 토요일 장문도 같은 프롬프트·같은 로봇이 만든다(`is_long_day`가 길이만 바꾼다).
         */
        fun ofRemote(): PassageSource = ROBOT
    }
}
